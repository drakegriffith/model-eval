#!/usr/bin/env python3
"""Context-rot micro-experiment.

Question: holding the task fixed, does a model's accuracy and instruction
adherence fall as the amount of irrelevant context in front of the task grows?

Design (paired, within-instance):
  - One instance = three planted config facts with random values and a question
    that requires all three.
  - The same instance is asked at every padding length, so the only thing that
    changes between conditions is how much unrelated text sits between the
    rules at the top and the question at the bottom.
  - Padding is the Python standard library's own source, concatenated in sorted
    order as a fake session log. It is inert: unlike this repo's task files, no
    line of it addresses a model, so nothing in the padding competes with the
    prompt for authority. Deterministic given a Python version.
  - Two scores per run, both deterministic: `correct` (the integer matches) and
    `format_ok` (the reply obeys the one-line output contract stated at the top
    of the prompt, and nowhere else).

Every invocation is subscription-authenticated through the local `claude` CLI
with API keys stripped from the child environment, tools disabled, MCP sealed
empty, and cwd set to an empty temp dir so no CLAUDE.md is discovered.

Usage:
  python3 experiments/context-rot/run.py --instances 10 --model sonnet
  python3 experiments/context-rot/run.py --summarize results/context-rot.jsonl
"""
from __future__ import annotations

import argparse
import json
import os
import random
import re
import subprocess
import sys
import sysconfig
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "results"
DEFAULT_LENGTHS = [2_000, 25_000, 50_000, 100_000, 200_000]
CHARS_PER_TOKEN = 2.7  # calibrated against measured usage on Python source
TEXT_SUFFIXES = {".py", ".md", ".yaml", ".yml", ".json", ".txt", ".toml", ".cfg", ".ts", ".js"}

CONTRACT = """\
OUTPUT CONTRACT (governs your entire reply, no exceptions):
- Reply with exactly one line.
- That line must be: ANSWER: <integer>
- No prose, no explanation, no restating the question, no code fences.

TASK BRIEF
Below is a session log: a long series of files that were read during an earlier
working session. Three deploy limits are defined somewhere inside it. At the end
of the log you will be asked to combine them. Read the log.

=== BEGIN SESSION LOG ===
"""

QUESTION = """\
=== END SESSION LOG ===

Using only the three deploy limits defined in the session log above, compute:

    MAX_INFLIGHT = retry_budget * shard_count + timeout_ms

Reply with the integer, following the output contract stated at the top of this
message.
"""

FACT_BLOCK = """\

=== FILE: deploy/{fname} ===
# generated by ops-sync, do not edit by hand
service: ingest-gateway
{key}: {value}
region: us-east-1

"""

FACTS = [
    ("retry_budget", "limits.yaml", (3, 9)),
    ("shard_count", "topology.yaml", (2, 9)),
    ("timeout_ms", "gateway.yaml", (100, 900)),
]
DEPTHS = [0.20, 0.50, 0.80]


def corpus() -> str:
    """Deterministic padding: the Python stdlib's sources, sorted, concatenated.

    Deliberately inert. The first cut of this experiment padded with this repo's
    own files, and one reply came back answering a question nobody asked: the
    padding was full of task prompts written at a model, and the model obeyed
    one. Padding has to be text that does not instruct.
    """
    root = Path(sysconfig.get_paths()["stdlib"])
    parts = []
    for p in sorted(root.rglob("*.py")):
        rel = p.relative_to(root).as_posix()
        if "test" in rel or "__pycache__" in rel or "site-packages" in rel:
            continue
        try:
            body = p.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        if any(k in body for k, _, _ in FACTS):
            continue  # keep the planted keys unique in the prompt
        parts.append(f"\n=== FILE: stdlib/{rel} ===\n{body}\n")
    text = "".join(parts)
    if not text:
        sys.exit("empty padding corpus")
    return text


def instance(seed: int) -> dict:
    rng = random.Random(seed)
    vals = {}
    for key, _fname, (lo, hi) in FACTS:
        vals[key] = rng.randrange(lo, hi + 1) * (50 if key == "timeout_ms" else 1)
    answer = vals["retry_budget"] * vals["shard_count"] + vals["timeout_ms"]
    return {"seed": seed, "values": vals, "answer": answer}


def build_prompt(pad: str, inst: dict, target_tokens: int) -> str:
    want = int(target_tokens * CHARS_PER_TOKEN)
    body = pad[:want] if want <= len(pad) else pad * (want // len(pad) + 1)
    body = body[:want]
    blocks = [
        FACT_BLOCK.format(fname=fname, key=key, value=inst["values"][key])
        for key, fname, _ in FACTS
    ]
    # insert deepest-first so earlier offsets stay valid
    for depth, block in sorted(zip(DEPTHS, blocks), reverse=True):
        cut = body.rfind("\n=== FILE:", 0, max(1, int(len(body) * depth)))
        cut = cut if cut > 0 else int(len(body) * depth)
        body = body[:cut] + block + body[cut:]
    return CONTRACT + body + QUESTION


def invoke(prompt: str, model: str, timeout: int) -> dict:
    env = {k: v for k, v in os.environ.items() if k not in ("ANTHROPIC_API_KEY", "OPENAI_API_KEY")}
    with tempfile.TemporaryDirectory() as cwd:
        started = time.time()
        proc = subprocess.run(
            [
                "claude", "-p",
                "--model", model,
                "--output-format", "json",
                "--allowed-tools", "",
                "--mcp-config", '{"mcpServers":{}}',
                "--strict-mcp-config",
            ],
            input=prompt, capture_output=True, text=True, cwd=cwd, env=env, timeout=timeout,
        )
        wall = time.time() - started
    if proc.returncode != 0:
        return {"error": (proc.stderr or proc.stdout)[-400:], "wall_s": round(wall, 1)}
    try:
        payload = json.loads(proc.stdout)
    except json.JSONDecodeError:
        return {"error": "unparseable CLI output", "wall_s": round(wall, 1)}
    u = payload.get("usage", {}) or {}
    return {
        "reply": payload.get("result", ""),
        "wall_s": round(wall, 1),
        "cost_usd": payload.get("total_cost_usd"),
        "input_tokens": (u.get("input_tokens", 0)
                         + u.get("cache_creation_input_tokens", 0)
                         + u.get("cache_read_input_tokens", 0)),
        "output_tokens": u.get("output_tokens", 0),
        "api_error": payload.get("api_error_status"),
    }


def score(reply: str, answer: int) -> dict:
    text = (reply or "").strip()
    fmt = bool(re.fullmatch(r"ANSWER:\s*-?\d+", text))
    nums = re.findall(r"ANSWER:\s*(-?\d+)", text)
    if not nums:
        nums = re.findall(r"-?\d+", text)
    return {"format_ok": fmt, "correct": bool(nums) and int(nums[-1]) == answer,
            "claimed": nums[-1] if nums else None}


def one_run(pad, inst, tokens, model, timeout):
    prompt = build_prompt(pad, inst, tokens)
    res = invoke(prompt, model, timeout)
    row = {"seed": inst["seed"], "target_tokens": tokens, "model": model,
           "answer": inst["answer"], "prompt_chars": len(prompt), **res}
    if "reply" in res:
        row.update(score(res["reply"], inst["answer"]))
        row["reply"] = res["reply"][:300]
    return row


def summarize(rows: list[dict]) -> None:
    by = {}
    for r in rows:
        if "correct" not in r:
            continue
        by.setdefault(r["target_tokens"], []).append(r)
    print(f"{'target':>8} {'measured_in':>12} {'n':>3} {'correct':>9} {'format_ok':>10} {'median_s':>9}")
    for t in sorted(by):
        rs = by[t]
        n = len(rs)
        meas = sorted(r.get("input_tokens", 0) for r in rs)[n // 2]
        acc = sum(r["correct"] for r in rs) / n
        fmt = sum(r["format_ok"] for r in rs) / n
        secs = sorted(r["wall_s"] for r in rs)[n // 2]
        print(f"{t:>8} {meas:>12,} {n:>3} {acc:>8.0%} {fmt:>9.0%} {secs:>9.1f}")
    errs = [r for r in rows if "error" in r]
    if errs:
        print(f"\n{len(errs)} run(s) errored:")
        for e in errs[:5]:
            print(f"  seed={e['seed']} tokens={e['target_tokens']}: {e['error'][:120]}")
    else:
        print("\n0 runs errored.")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--instances", type=int, default=10)
    ap.add_argument("--model", default="sonnet")
    ap.add_argument("--lengths", type=int, nargs="+", default=DEFAULT_LENGTHS)
    ap.add_argument("--workers", type=int, default=5)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--out", default=None)
    ap.add_argument("--summarize", default=None)
    args = ap.parse_args()

    if args.summarize:
        summarize([json.loads(l) for l in Path(args.summarize).read_text().splitlines() if l.strip()])
        return

    OUT.mkdir(parents=True, exist_ok=True)
    out = Path(args.out) if args.out else OUT / f"context-rot-{args.model}.jsonl"
    pad = corpus()
    print(f"padding corpus: {len(pad):,} chars ({len(pad)/CHARS_PER_TOKEN:,.0f} est tokens), "
          f"python {sys.version.split()[0]}")
    insts = [instance(1000 + i) for i in range(args.instances)]
    jobs = [(i, t) for t in args.lengths for i in insts]
    print(f"{len(jobs)} runs: {args.instances} instances x {len(args.lengths)} lengths, model={args.model}")

    rows, done = [], 0
    with out.open("w") as fh, ThreadPoolExecutor(max_workers=args.workers) as pool:
        futs = [pool.submit(one_run, pad, i, t, args.model, args.timeout) for i, t in jobs]
        for f in futs:
            row = f.result()
            rows.append(row)
            fh.write(json.dumps(row) + "\n")
            fh.flush()
            done += 1
            mark = "!" if "error" in row else ("." if row.get("correct") else "x")
            print(mark, end="", flush=True)
            if done % 25 == 0:
                print(f" {done}/{len(jobs)}", flush=True)
    spent = sum(r.get("cost_usd") or 0 for r in rows)
    print(f"\n\nwrote {out}  (list-price equivalent ${spent:.2f})\n")
    summarize(rows)


if __name__ == "__main__":
    main()
