#!/usr/bin/env bash
# verify_clis.sh — probe the installed `claude` and `codex` CLIs and (re)generate
# runner/CLI-FACTS.md with the discovered headless invocation, model ids, effort
# control, permission-bypass flags, and JSON token-usage field names.
#
# Usage:
#   bash verify_clis.sh            # help-probe only (no tokens spent)
#   bash verify_clis.sh --smoke    # also make ONE tiny real call per CLI
#
# Everything discovered here is what run.py / judge.py rely on. If a CLI upgrades
# and a flag/field moves, re-run this and reconcile CLI-FACTS.md before a real sweep.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/CLI-FACTS.md"
SMOKE=0
[ "${1:-}" = "--smoke" ] && SMOKE=1

# --- CLI presence probe: degrade gracefully with a clear FAIL, never crash -----
have_claude=1; have_codex=1
if ! command -v claude >/dev/null 2>&1; then
  have_claude=0
  echo "FAIL: 'claude' CLI not found on PATH — run.py (fable) + the claude judge cannot run." >&2
  echo "      install/login the Claude Code CLI, then re-run: bash verify_clis.sh --smoke" >&2
fi
if ! command -v codex >/dev/null 2>&1; then
  have_codex=0
  echo "FAIL: 'codex' CLI not found on PATH — run.py (sol) + the codex judge cannot run." >&2
  echo "      install/login the Codex CLI, then re-run: bash verify_clis.sh --smoke" >&2
fi
if [ "$have_claude" = 0 ] && [ "$have_codex" = 0 ]; then
  echo "FAIL: neither CLI present; nothing to probe. Aborting without writing CLI-FACTS.md." >&2
  exit 1
fi

claude_ver="$([ "$have_claude" = 1 ] && claude --version 2>&1 | head -1 || echo 'MISSING (claude CLI not on PATH)')"
codex_ver="$([ "$have_codex" = 1 ] && codex --version 2>&1 | head -1 || echo 'MISSING (codex CLI not on PATH)')"
codex_model="$(grep -E '^model[[:space:]]*=' "$HOME/.codex/config.toml" 2>/dev/null | head -1 | sed 's/.*=//; s/[" ]//g')"
codex_effort="$(grep -E '^model_reasoning_effort' "$HOME/.codex/config.toml" 2>/dev/null | head -1 | sed 's/.*=//; s/[" ]//g')"

claude_smoke="(not run — pass --smoke to capture)"
codex_smoke="(not run — pass --smoke to capture)"
if [ "$SMOKE" = "1" ]; then
  echo "verify_clis: running smoke calls (this spends a few tokens)..." >&2
  cd /tmp
  if [ "$have_claude" = 1 ]; then
    claude_smoke="$(claude -p 'reply with the single word ok' --output-format json \
        --model claude-fable-5 --effort low --dangerously-skip-permissions 2>&1 | head -c 4000)"
  else
    claude_smoke="(skipped — claude CLI missing)"
  fi
  if [ "$have_codex" = 1 ]; then
    d="$(mktemp -d)"; ( cd "$d" && git init -q )
    codex_smoke="$(cd "$d" && codex exec --json --skip-git-repo-check \
        --dangerously-bypass-approvals-and-sandbox 'reply with the single word ok' 2>&1 | tail -c 2000)"
    rm -rf "$d"
  else
    codex_smoke="(skipped — codex CLI missing)"
  fi
fi

cat > "$OUT" <<EOF
# CLI-FACTS.md — discovered $(date -u +%Y-%m-%dT%H:%M:%SZ)

Auto-generated by \`runner/verify_clis.sh\`. Both CLIs run on Drake's **subscriptions**;
run.py/judge.py NEVER set \`ANTHROPIC_API_KEY\` or \`OPENAI_API_KEY\`.

Detected versions:
- claude: \`$claude_ver\`
- codex : \`$codex_ver\`

## Claude (Claude Code) — the "fable" model

| Concern | Answer |
|---|---|
| Headless invocation | \`claude -p "<prompt>" --output-format json\` |
| Model select | \`--model claude-fable-5\` (alias \`fable\`; also \`opus\` / \`claude-opus-4-8\` for the judge) |
| Effort control | \`--effort <low\|medium\|high\|xhigh\|max>\` |
| Permission bypass | \`--dangerously-skip-permissions\` (runs with cwd = the scratch working copy) |
| Output shape | single JSON object, \`{"type":"result", ...}\` |
| tokens_in field | \`usage.input_tokens\` |
| tokens_out field | \`usage.output_tokens\` |
| turns field | \`num_turns\` |
| final text | \`result\` |
| cost (bonus) | \`total_cost_usd\`, per-model under \`modelUsage["claude-fable-5"]\` |

Exact command run.py uses (cwd = scratch copy):
\`\`\`
claude -p "<composed prompt>" --output-format json \\
  --model claude-fable-5 --effort <effort> --dangerously-skip-permissions
\`\`\`
Note: \`--bare\` is NOT used — it forces ANTHROPIC_API_KEY auth and would break subscription auth.
The global ~/.claude/CLAUDE.md still loads for every run (constant across all cells, so fair);
the benchmark harness is delivered per-run as a CLAUDE.md/AGENTS.md dropped into the scratch cwd.

## Codex (codex-cli) — the "sol" model

| Concern | Answer |
|---|---|
| Headless invocation | \`codex exec [OPTIONS] "<prompt>"\` (stdin = /dev/null) |
| Model select | \`-m gpt-5.6-sol\` |
| **Sol model id** | \`$codex_model\`  ← from ~/.codex/config.toml (\`model = "gpt-5.6-sol"\`, \`review_model = "gpt-5.6-sol"\`) — CONFIRMED |
| Effort control | \`-c model_reasoning_effort=<low\|medium\|high>\` (config default: \`$codex_effort\`; codex has NO xhigh/max) |
| Permission bypass | \`--dangerously-bypass-approvals-and-sandbox\` (NOTE: \`codex exec\` does NOT accept \`-a/--ask-for-approval\`; that lives on the top-level \`codex\` cmd) |
| JSON output | \`--json\` → JSONL event stream on stdout |
| tokens_in field | \`turn.completed\` event → \`usage.input_tokens\` (sum across turn.completed events) |
| tokens_out field | \`turn.completed\` event → \`usage.output_tokens\` |
| turns | count of \`turn.completed\` events |
| final text | \`item.completed\` event where \`item.type == "agent_message"\` → \`item.text\` |

Exact command run.py uses (cwd = scratch copy, stdin = /dev/null):
\`\`\`
codex exec --json --skip-git-repo-check --dangerously-bypass-approvals-and-sandbox \\
  -m gpt-5.6-sol -c model_reasoning_effort=<effort> "<composed prompt>"
\`\`\`

## Sample parsed usage (smoke calls)

Prompt for both: \`reply with the single word ok\`.

### claude -p --output-format json
\`\`\`
$claude_smoke
\`\`\`
Parsed: tokens_in = \`usage.input_tokens\`, tokens_out = \`usage.output_tokens\`, turns = \`num_turns\`.

### codex exec --json
\`\`\`
$codex_smoke
\`\`\`
Parsed: from the \`turn.completed\` event, tokens_in = \`usage.input_tokens\`, tokens_out = \`usage.output_tokens\`; turns = number of \`turn.completed\` events.

## Flags NOT to use / gotchas
- Never pass \`--bare\` to claude (forces API-key auth → breaks subscription).
- \`codex exec\` rejects \`--ask-for-approval\`; use \`--dangerously-bypass-approvals-and-sandbox\`.
- codex prints "Reading additional input from stdin..." if stdin is a pipe; run.py sets stdin=/dev/null.
- codex effort is limited to low/medium/high. Fable supports low/medium/high/xhigh/max.
- Both write into the current working directory; run.py always launches them with cwd set to the per-run scratch copy so edits land there and \`git diff\` measures them.
EOF

echo "wrote $OUT"
